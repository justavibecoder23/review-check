import { readFile, writeFile } from 'node:fs/promises';

// Derive the mobile above-the-fold rules from the existing stylesheets, so
// header/mascot changes retain one source of truth. Full styles load afterwards.
const sources = ['auth.css', 'chatbot.css'];
const target = new URL('../public/home-widgets.css', import.meta.url);
const criticalSelector = /^(?:\.header-(?:auth|utilities|contact|actions)|\.header-inner\s*>\s*\.brand|\.auth-button|\.account-chip|\.chatbot-trigger|\.realviewee-(?:sprite|stage|companion|character|state-speech|speech))(?:\b|[-\s:.\[>])/;

function blocks(css) {
  const result = [];
  let start = 0;
  let open = -1;
  let depth = 0;
  let quote = '';
  let comment = false;
  for (let index = 0; index < css.length; index += 1) {
    const character = css[index];
    if (comment) {
      if (character === '*' && css[index + 1] === '/') { comment = false; index += 1; }
      continue;
    }
    if (quote) {
      if (character === '\\') index += 1;
      else if (character === quote) quote = '';
      continue;
    }
    if (character === '/' && css[index + 1] === '*') { comment = true; index += 1; continue; }
    if (character === '"' || character === "'") { quote = character; continue; }
    if (character === '{') {
      if (depth === 0) open = index;
      depth += 1;
    } else if (character === '}') {
      depth -= 1;
      if (depth === 0) {
        result.push({ header: css.slice(start, open).replace(/\/\*[\s\S]*?\*\//g, '').trim(), body: css.slice(open + 1, index) });
        start = index + 1;
      }
    }
  }
  if (depth !== 0 || quote || comment) throw new Error('Unbalanced source stylesheet');
  return result;
}

function selectCritical(css) {
  return blocks(css).flatMap(({ header, body }) => {
    if (/^@media\b/.test(header)) {
      const children = selectCritical(body);
      return children ? [`${header} {\n${children}\n}`] : [];
    }
    if (/^@keyframes realviewee-/.test(header)) return [`${header} {${body}}`];
    if (header.startsWith('@')) return [];
    const selectors = header.split(',').map((selector) => selector.trim()).filter((selector) => criticalSelector.test(selector));
    return selectors.length ? [`${selectors.join(',\n')} {${body}}`] : [];
  }).join('\n');
}

const css = await Promise.all(sources.map(async (name) => selectCritical((await readFile(new URL(`../public/${name}`, import.meta.url), 'utf8')).replace(/\r\n?/g, '\n'))));
const output = `/* Generated by npm run build:home-css. Edit auth.css/chatbot.css, then regenerate. */\n${css.join('\n')}\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('home-widgets.css is stale; run npm run build:home-css');
} else {
  await writeFile(target, output);
}
